-- 실험용 합성 CRM (docs/lab.md). 일반 앱이 가질 법한 제약(외래 키, CHECK)만 둔다.
-- 정규화 이메일 UNIQUE 같은 강한 결정론적 제약은 비교 arm A의 몫이라 여기 넣지 않는다.
-- 기록 단계에 넣으면 쓰기 스트림 자체가 달라진다.

CREATE TABLE accounts (
  id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL,
  domain   text NOT NULL,
  industry text NOT NULL
);

CREATE TABLE contacts (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id        int NOT NULL REFERENCES accounts,
  name              text NOT NULL,
  email             text NOT NULL,
  phone             text,
  title             text,
  status            text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','churned')),
  marketing_consent boolean NOT NULL DEFAULT false,
  consent_source    text,
  notes             text,
  updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE deals (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id int NOT NULL REFERENCES accounts,
  contact_id int REFERENCES contacts,
  stage      text NOT NULL CHECK (stage IN ('open','won','lost')),
  amount     int NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE activities (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id int NOT NULL REFERENCES contacts,
  kind       text NOT NULL,
  body       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON contacts (account_id);
CREATE INDEX ON contacts (lower(email));
CREATE INDEX ON deals (account_id);
CREATE INDEX ON activities (contact_id);
